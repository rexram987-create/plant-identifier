function getLocation() {
  return new Promise(resolve => {
    if (!navigator.geolocation || navigator.onLine === false) return resolve(null);
    navigator.geolocation.getCurrentPosition(
      p => resolve({lat: p.coords.latitude, lng: p.coords.longitude}),
      () => resolve(null),
      {enableHighAccuracy: false, timeout: 5000, maximumAge: 3600000}
    );
  });
}
async function resolveINatTaxonId(name) {
  const d = await fetchJson('https://api.inaturalist.org/v1/taxa?q=' + encodeURIComponent(name) + '&per_page=10');
  const exact = (d.results || []).find(x => String(x.name || '').trim().toLowerCase() === name.trim().toLowerCase());
  return Number(exact?.id) || null;
}
async function nearbyCount(name, loc, radius) {
  const taxonId = await resolveINatTaxonId(name);
  if (!taxonId) return 0;
  const params = new URLSearchParams({taxon_id: String(taxonId), lat: String(loc.lat), lng: String(loc.lng), radius: String(radius), per_page: '1', quality_grade: 'research'});
  const d = await fetchJson('https://api.inaturalist.org/v1/observations?' + params);
  return Number(d.total_results || 0);
}
async function rerankByGeography(top) {
  const loc = await getLocation();
  if (!loc) return {items: top, used: false, hasData: false, radius: 0};
  const radius = 150;
  const counts = await Promise.all(top.map(r => nearbyCount(r.name, loc, radius).catch(() => null)));
  const complete = counts.every(count => count !== null);
  const maxCount = complete ? Math.max(...counts, 0) : 0;
  const items = top.map((r, i) => ({...r, nearbyCount: counts[i], regionalScore: maxCount > 0 ? Math.log1p(counts[i]) / Math.log1p(maxCount) : 0}));
  if (maxCount > 0) items.sort((a, b) => (b.probability * .68 + b.regionalScore * .32) - (a.probability * .68 + a.regionalScore * .32));
  return {items, used: true, hasData: maxCount > 0, radius, incomplete: !complete};
}
